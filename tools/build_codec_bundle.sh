#!/bin/sh
# Build clients/atlas_codec.bundle.js (opt-in binary atlas/1 codec for client.html) from the Artist's codec:
#   js/atlas_browser.js (glue + AtlasCodec) + the wasm, base64-embedded. Output is ~0.5 MB and is NOT committed (.gitignore).
# usage: tools/build_codec_bundle.sh <codec dir containing js/atlas_browser.js> [wasm path]
set -e
D=${1:?codec dir}; W=${2:-$D/target/wasm32-unknown-unknown/release/atlas_codec.wasm}
O=$(dirname "$0")/../clients/atlas_codec.bundle.js
{ echo "/* generated by tools/build_codec_bundle.sh from $(basename "$D")/js/atlas_browser.js + $(basename "$W"); do not edit */"
  cat "$D/js/atlas_browser.js"
  printf '\n;window.AtlasCodec=AtlasCodec;window.ATLAS_CODEC_WASM="'; base64 -w0 "$W"; echo '";'; } > "$O"
wc -c "$O"
